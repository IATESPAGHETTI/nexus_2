"""Recovery Agent (Phase 8).

Receives a DIAGNOSED incident's leading Hypothesis (plus the Root-Cause
Critic's supporting Critique) and proposes a bounded RecoveryPlan (root
CLAUDE.md section 20). Reached only over real A2A in production use
(agents/recovery/a2a_service.py); orchestrator/recovery.py never imports this
module directly -- same rule as Evidence/Critic (agents/CLAUDE.md).

Like the Evidence Agent and Root-Cause Critic, this is a `ReasoningAgent`
(agents/common/reasoning_agent.py): NO MCP tools, NO ability to call anything
in production/ itself. It can only ever emit a JSON *proposal*. This is what
makes "never execute arbitrary shell commands generated by an LLM" (root
CLAUDE.md section 20) structurally true rather than a prompt-only promise --
the only code with real execution capability is guardrails/executor.py, which
independently re-validates every action against its own authoritative
allowlist (guardrails/config.py's ALLOWED_ACTIONS) before ever calling out to
production/. `ACTION_CATALOG` below is this agent's own local copy of that
catalog, used only to constrain the model's proposal and to drop (never
trust) any action name it invents that isn't in this list -- the same
evidence/hypothesis-id-dropping principle as agents/evidence/agent.py's
build_hypotheses().
"""

from __future__ import annotations

import json
import sys
import time
import uuid
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "common"))

from reasoning_agent import ReasoningAgent  # noqa: E402

sys.path.insert(0, str(Path(__file__).resolve().parents[2]))
from nexus_models import RecoveryPlan, validated  # noqa: E402

AGENT_NAME = "recovery_agent"

# Kept in sync with guardrails/config.py's ALLOWED_ACTIONS by convention, not
# by import (dependency isolation -- agents/ and guardrails/ have separate
# venvs/lifecycles). guardrails/policy.py is the actual, authoritative,
# independently-enforced allowlist; this is only what the model is told it
# may propose.
ACTION_CATALOG = {
    "restart_service": "restarts the service process; clears ONLY transient resource-exhaustion or stuck-dependency faults. It does NOT fix slow database queries, bad deployments or configuration errors. No params",
    "rollback_deployment": "reverts to a named prior version; params: target_version (string, a real version from the change history evidence given)",
    "reset_config": "resets configuration to the last known-good value; no params",
    "scale_resources": "adds capacity; this is the action that relieves SLOW DATABASE QUERIES (database slowdown) and resource exhaustion. No params",
}
VALID_RISK_LEVELS = ("LOW", "MEDIUM", "HIGH")

INSTRUCTION = (
    "You are the NEXUS Recovery Agent. You will be given a JSON object with "
    "keys \"hypothesis\" (the diagnosed root-cause Hypothesis), \"critique\" "
    "(the Root-Cause Critic's supporting Critique), and \"evidence_pool\" (a "
    "JSON array of ALL real evidence items gathered by the diagnostic agents "
    "-- each with evidence_id, tool, arguments, result; a get_recent_deployments "
    "result's \"changes\" list, if present, is your ONLY real source for a "
    "prior known-good version string). Propose exactly ONE bounded recovery "
    "plan as a single JSON object (no prose, no markdown fences) with these "
    "keys: \"actions\" (a JSON array of 1 to 3 objects, each with \"action\" "
    "-- one of exactly: " + ", ".join(ACTION_CATALOG) + " -- and \"params\" "
    "(object; rollback_deployment REQUIRES params.target_version, a real "
    "version string copied EXACTLY from evidence_pool's deployment history -- "
    "if evidence_pool has no deployment history, do NOT propose "
    "rollback_deployment at all; every other action takes params: {}) and "
    "\"rationale\" (string)), \"risk_level\" (one of \"LOW\", \"MEDIUM\", "
    "\"HIGH\" -- be conservative, prefer LOW/MEDIUM), \"blast_radius\" (a short "
    "string describing what this plan could affect if it goes wrong), and "
    "\"rollback_plan\" (a short string describing how to undo this plan if it "
    "makes things worse). If the input has a \"remedy_guidance\" array, each entry names a symptom the evidence shows and the actions guardrails know fix it: choose your action from those unless the evidence clearly shows a different cause. NEVER propose an action outside the exact list "
    "given above -- there is no other action available. Choose actions that "
    "plausibly address the hypothesis' stated root cause using only the real "
    "evidence already given to you. Match the action to the SYMPTOM using the "
    "action descriptions above: if the diagnosed cause is slow database "
    "queries or high query latency, propose scale_resources, NOT "
    "restart_service (a restart does not clear it). Never invent a version "
    "number that doesn't appear verbatim in evidence_pool."
)

DEFAULT_QUESTION = json.dumps({"hypothesis": {}, "critique": {}, "evidence_pool": []})

DESCRIPTION = (
    "NEXUS Recovery Agent: proposes a bounded RecoveryPlan (allowlisted "
    "actions only) for a diagnosed incident. Has no tools and cannot execute "
    "anything itself -- guardrails/ independently validates and executes."
)


def _now_iso() -> str:
    return time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime())


def build_recovery_plan(hypothesis: dict, critique: dict, raw_model_output, max_actions: int = 3) -> dict:
    """Structurally enforces the RecoveryPlan shape. Any action not in
    `ACTION_CATALOG` is dropped (never trusted); `risk_level` outside the
    valid enum falls back to the conservative default `MEDIUM`; the action
    list is capped at `max_actions`. `plan_id` and `status` are always
    assigned here, never taken from the model.
    """
    if not isinstance(raw_model_output, dict):
        raw_model_output = {}

    hypothesis = hypothesis if isinstance(hypothesis, dict) else {}
    critique = critique if isinstance(critique, dict) else {}

    raw_actions = raw_model_output.get("actions")
    raw_actions = raw_actions if isinstance(raw_actions, list) else []

    actions: list[dict] = []
    dropped = 0
    for index, item in enumerate(raw_actions):
        if not isinstance(item, dict):
            dropped += 1
            continue
        name = item.get("action")
        if name not in ACTION_CATALOG:
            dropped += 1
            continue
        params = item.get("params")
        params = params if isinstance(params, dict) else {}
        rationale = item.get("rationale")
        actions.append(
            {
                "action": name,
                "params": params,
                "rationale": str(rationale) if rationale else "(no rationale provided)",
            }
        )
        if len(actions) >= max_actions:
            dropped += len(raw_actions) - index - 1
            break

    risk_level = raw_model_output.get("risk_level")
    if risk_level not in VALID_RISK_LEVELS:
        risk_level = "MEDIUM"

    blast_radius = raw_model_output.get("blast_radius")
    rollback_plan = raw_model_output.get("rollback_plan")

    plan = {
        "plan_id": f"RP-{uuid.uuid4().hex[:8]}",
        "hypothesis_id": hypothesis.get("hypothesis_id"),
        "actions": actions,
        "risk_level": risk_level,
        "blast_radius": str(blast_radius) if blast_radius else "not specified by recovery agent",
        "rollback_plan": str(rollback_plan) if rollback_plan else "not specified by recovery agent",
        "status": "PROPOSED",
        "dropped_invalid_actions": dropped,
        "created_at": _now_iso(),
    }
    return validated(RecoveryPlan, plan)


class RecoveryAgent:
    """Duck-typed like `DiagnosticAgent`/`EvidenceAgent`/`CriticAgent`
    (`build_adk_agent`, `default_question`, async `investigate`) so
    `agents/common/a2a_server.py` serves it unmodified."""

    agent_name = AGENT_NAME
    default_question = DEFAULT_QUESTION

    def __init__(self) -> None:
        self._reasoner = ReasoningAgent(
            agent_name=AGENT_NAME,
            instruction=INSTRUCTION,
            default_question=DEFAULT_QUESTION,
            description=DESCRIPTION,
        )

    def build_adk_agent(self):
        return self._reasoner.build_adk_agent()

    async def investigate(self, question: str) -> dict:
        try:
            payload = json.loads(question)
        except json.JSONDecodeError:
            payload = {}
        if not isinstance(payload, dict):
            payload = {}
        hypothesis = payload.get("hypothesis") or {}
        critique = payload.get("critique") or {}

        raw = await self._reasoner.investigate(question)
        plan = build_recovery_plan(hypothesis, critique, raw.get("parsed"))
        return {"recovery_plan": plan, "usage": raw.get("usage"), "monitoring": raw.get("monitoring")}


recovery_agent = RecoveryAgent()


async def propose(hypothesis: dict, critique: dict, evidence_pool: list[dict] | None = None) -> dict:
    """Direct in-process helper -- used only by this package's own unit tests
    and by the A2A server that hosts this exact object. Never imported by
    orchestrator/ (which must reach this agent only over real A2A)."""
    question = json.dumps({"hypothesis": hypothesis, "critique": critique, "evidence_pool": evidence_pool or []})
    result = await recovery_agent.investigate(question)
    return result["recovery_plan"]
